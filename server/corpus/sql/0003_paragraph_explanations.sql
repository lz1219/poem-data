-- Append-only explanation revisions; original corpus text and source notes remain separate.
CREATE TABLE IF NOT EXISTS public.corpus_paragraph_explanation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paragraph_id integer NOT NULL REFERENCES public.paragraph(id) ON DELETE RESTRICT,
    unit_id integer NOT NULL REFERENCES public.text_unit(id) ON DELETE RESTRICT,
    edition_id integer NOT NULL REFERENCES public.edition(id) ON DELETE RESTRICT,
    revision integer NOT NULL CHECK (revision > 0),
    source_revision bigint NOT NULL CHECK (source_revision > 0),
    source_sha256 text NOT NULL CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
    state text NOT NULL CHECK (state IN ('unreviewed', 'withdrawn')),
    content jsonb NOT NULL,
    generation jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (paragraph_id, revision)
);
CREATE INDEX IF NOT EXISTS corpus_paragraph_explanation_unit_idx
    ON public.corpus_paragraph_explanation(unit_id, paragraph_id, revision DESC);
